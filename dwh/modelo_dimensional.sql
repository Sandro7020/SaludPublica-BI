-- =====================================================================
-- Modelo dimensional - Hospital SanaSalud (PostgreSQL)
-- Orden: dimensiones -> tablas de hechos -> tabla aislada
-- Convenciones: NUMBER -> NUMERIC, FLOAT -> DOUBLE PRECISION,
--               llaves sustitutas (SK) autogeneradas con IDENTITY
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS dwh;

-- Limpieza para poder re-ejecutar el script (solo tablas de este modelo)
DROP TABLE IF EXISTS dwh.fact_tratamiento              CASCADE;
DROP TABLE IF EXISTS dwh.fact_diagnostico              CASCADE;
DROP TABLE IF EXISTS dwh.fact_intervencion             CASCADE;
DROP TABLE IF EXISTS dwh.fact_facturacion              CASCADE;
DROP TABLE IF EXISTS dwh.dim_registro_epidemiologico   CASCADE;
DROP TABLE IF EXISTS dwh.dim_medicamento               CASCADE;
DROP TABLE IF EXISTS dwh.dim_proveedor                 CASCADE;
DROP TABLE IF EXISTS dwh.dim_tratamiento               CASCADE;
DROP TABLE IF EXISTS dwh.dim_diagnostico               CASCADE;
DROP TABLE IF EXISTS dwh.dim_medico                    CASCADE;
DROP TABLE IF EXISTS dwh.dim_paciente                  CASCADE;
DROP TABLE IF EXISTS dwh.dim_historia_medica           CASCADE;
DROP TABLE IF EXISTS dwh.dim_estado_factura            CASCADE;
DROP TABLE IF EXISTS dwh.dim_tipo_servicio             CASCADE;
DROP TABLE IF EXISTS dwh.dim_intervencion              CASCADE;
DROP TABLE IF EXISTS dwh.dim_riesgo                    CASCADE;
DROP TABLE IF EXISTS dwh.dim_personal_sanit            CASCADE;
DROP TABLE IF EXISTS dwh.dim_area                      CASCADE;
DROP TABLE IF EXISTS dwh.dim_poliza                    CASCADE;
DROP TABLE IF EXISTS dwh.dim_tiempo                    CASCADE;

-- =====================================================================
-- DIMENSIONES
-- =====================================================================

CREATE TABLE dwh.dim_tiempo (
    sk_dim_tiempo   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_completa  DATE    NOT NULL UNIQUE,
    dia             INTEGER NOT NULL CHECK (dia BETWEEN 1 AND 31),
    mes             INTEGER NOT NULL CHECK (mes BETWEEN 1 AND 12),
    annio           INTEGER NOT NULL
);

CREATE TABLE dwh.dim_poliza (
    sk_dim_poliza   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empresa         VARCHAR(50),
    tipo_poliza     VARCHAR(20),
    hospitalizacion BOOLEAN,
    cirugia         BOOLEAN,
    maternidad      BOOLEAN,
    radiografias    BOOLEAN,
    examenes        BOOLEAN,
    ambulancia      BOOLEAN,
    cobertura       DOUBLE PRECISION,
    aprobada        BOOLEAN
);

CREATE TABLE dwh.dim_area (
    sk_dim_area                 INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_area                     NUMERIC,
    piso                        INTEGER,
    pasillo                     INTEGER,
    id_especialidad             INTEGER,
    descripcion_especialidad    VARCHAR(20)
);

CREATE TABLE dwh.dim_personal_sanit (
    sk_dim_personal_sanit       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ci_personal                 NUMERIC,
    nombre                      VARCHAR(20),
    apellido                    VARCHAR(20),
    funcion                     VARCHAR(25),
    area_id                     NUMERIC,
    sexo_id                     NUMERIC,
    descripcion_sexo            VARCHAR(2),
    edo_civil_id                NUMERIC,
    descrip_edo_civil           VARCHAR,
    nacionalidad                VARCHAR(20),
    piso                        INTEGER,
    pasillo                     INTEGER,
    id_especialidad             INTEGER,
    descripcion_especialidad    VARCHAR(20)
);

CREATE TABLE dwh.dim_riesgo (
    sk_dim_riesgo       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_riesgo          NUMERIC,
    descripcion_riesgo  VARCHAR(20)
);

CREATE TABLE dwh.dim_intervencion (
    sk_dim_intervencion         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_intervencion             NUMERIC,
    descripcion_intervencion    VARCHAR(20),
    tipo_intervencion           VARCHAR(5)
);

CREATE TABLE dwh.dim_tipo_servicio (
    sk_dim_tipo_servicio        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_tipo_servicio           NUMERIC,
    descripcion_tipo_servicio   VARCHAR(20)
);

CREATE TABLE dwh.dim_estado_factura (
    sk_dim_estado_factura           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_estado_factura              NUMERIC,
    descripcion_estado_factura      VARCHAR(20)
);

CREATE TABLE dwh.dim_historia_medica (
    sk_dim_historia_medica  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_historia            NUMERIC,
    peso_actual             DOUBLE PRECISION,
    peso_ideal              DOUBLE PRECISION,
    tension                 VARCHAR(20),
    fumador                 BOOLEAN,
    prob_respiratorio       BOOLEAN
);

CREATE TABLE dwh.dim_paciente (
    sk_dim_paciente     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula              NUMERIC,
    nombre              VARCHAR(20),
    apellido            VARCHAR(20),
    fecha_nacimiento    DATE,
    tipo_sangre         VARCHAR(5),   -- el diagrama dice DATE; se asume error (ej. 'O+')
    sexo_id             NUMERIC,
    descripcion_sexo    VARCHAR(2),
    edo_civil_id        NUMERIC,
    descrip_edo_civil   VARCHAR,
    nacionalidad        VARCHAR(20),
    hipertenso          BOOLEAN,
    artritis            BOOLEAN,
    osteoporosis        BOOLEAN,
    diabetes            BOOLEAN
);

CREATE TABLE dwh.dim_medico (
    sk_dim_medico        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cedula               NUMERIC,
    cod_colegio_medicos  NUMERIC,
    nombre               VARCHAR(20),
    apellido             VARCHAR(20),
    fecha_nacimiento     DATE,
    fecha_contratacion   DATE,
    sexo_id              NUMERIC,
    descripcion_sexo     VARCHAR(2),
    edo_civil_id         NUMERIC,
    descrip_edo_civil    VARCHAR,
    anos_exper           NUMERIC,
    id_area              NUMERIC,
    piso                 INTEGER,
    pasillo              INTEGER
);

CREATE TABLE dwh.dim_diagnostico (
    sk_dim_diagnostico       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_diagnostico           NUMERIC,
    descripcion_diagnostico  VARCHAR(20),
    tipo_diagnostico         VARCHAR(5),
    costo                    DOUBLE PRECISION
);

CREATE TABLE dwh.dim_tratamiento (
    sk_dim_tratamiento       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tratamiento           NUMERIC,
    descripcion_tratamiento  VARCHAR(20),
    costo                    DOUBLE PRECISION
);

CREATE TABLE dwh.dim_proveedor (
    sk_dim_proveedor        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proveedor            NUMERIC,
    nombre                  VARCHAR(20),
    rif                     VARCHAR(20),
    telefono                VARCHAR(20),
    tipo_proveedor_id       NUMERIC,
    descripcion_tipo_provee VARCHAR(20),
    edo_civil_id            NUMERIC,
    descrip_edo_civil       VARCHAR,
    ciudad_id               NUMERIC,
    nombre_ciudad           VARCHAR(20),
    direccion               VARCHAR(50),
    tipo_proveedor          INTEGER,
    descrip_tipo            VARCHAR(50),
    id_estado               INTEGER,
    descrip_estado          VARCHAR(50)
);

CREATE TABLE dwh.dim_medicamento (
    sk_dim_medicina      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_medicina          NUMERIC,
    nombre_medicina      VARCHAR(20),
    presentacion         VARCHAR(30),
    posologia            VARCHAR(50),
    efectos_secundarios  VARCHAR(50),
    -- referencia a dim_proveedor(sk_dim_proveedor), conserva el nombre del diagrama
    id_proveedor         INTEGER REFERENCES dwh.dim_proveedor (sk_dim_proveedor)
);

-- =====================================================================
-- TABLAS DE HECHOS
-- =====================================================================

CREATE TABLE dwh.fact_facturacion (
    sk_fact_facturacion         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sk_dim_paciente             INTEGER NOT NULL REFERENCES dwh.dim_paciente (sk_dim_paciente),
    sk_dim_tipo_servicio        INTEGER NOT NULL REFERENCES dwh.dim_tipo_servicio (sk_dim_tipo_servicio),
    sk_dim_fecha_facturacion    INTEGER NOT NULL REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    sk_dim_poliza               INTEGER REFERENCES dwh.dim_poliza (sk_dim_poliza),
    sk_dim_estado_factura       INTEGER NOT NULL REFERENCES dwh.dim_estado_factura (sk_dim_estado_factura),
    sk_dim_fecha_historia_medica INTEGER REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    -- Supuesto: el diagrama relaciona dim_historia_medica con este hecho
    -- pero no muestra columna FK propia; se agrega aqui.
    sk_dim_historia_medica      INTEGER REFERENCES dwh.dim_historia_medica (sk_dim_historia_medica),
    sk_dim_area                 INTEGER NOT NULL REFERENCES dwh.dim_area (sk_dim_area),
    sk_fecha_inicio             INTEGER NOT NULL REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    costo_bolivares             DOUBLE PRECISION,
    nro_poliza                  INTEGER,   -- dimension degenerada
    dias_cubiertos_seguro       NUMERIC,
    cant_dias                   NUMERIC,
    numero_cama                 INTEGER
);

CREATE TABLE dwh.fact_intervencion (
    sk_dim_medico               INTEGER NOT NULL REFERENCES dwh.dim_medico (sk_dim_medico),
    sk_dim_paciente             INTEGER NOT NULL REFERENCES dwh.dim_paciente (sk_dim_paciente),
    sk_dim_intervencion         INTEGER NOT NULL REFERENCES dwh.dim_intervencion (sk_dim_intervencion),
    sk_dim_personal_sanit_prim  INTEGER NOT NULL REFERENCES dwh.dim_personal_sanit (sk_dim_personal_sanit),
    sk_dim_personal_sanit_secun INTEGER REFERENCES dwh.dim_personal_sanit (sk_dim_personal_sanit),
    sk_dim_fecha_practica       INTEGER NOT NULL REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    sk_dim_riesgo               INTEGER REFERENCES dwh.dim_riesgo (sk_dim_riesgo),
    gastos_equipos              DOUBLE PRECISION,
    costo                       DOUBLE PRECISION,
    honorario_equipo            DOUBLE PRECISION,
    duracion                    DOUBLE PRECISION,
    PRIMARY KEY (sk_dim_medico, sk_dim_paciente, sk_dim_intervencion,
                 sk_dim_personal_sanit_prim, sk_dim_fecha_practica)
);

CREATE TABLE dwh.fact_diagnostico (
    sk_dim_medico               INTEGER NOT NULL REFERENCES dwh.dim_medico (sk_dim_medico),
    sk_dim_paciente             INTEGER NOT NULL REFERENCES dwh.dim_paciente (sk_dim_paciente),
    sk_dim_diagnostico          INTEGER NOT NULL REFERENCES dwh.dim_diagnostico (sk_dim_diagnostico),
    sk_dim_fecha_elaboracion    INTEGER NOT NULL REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    num_ingreso                 NUMERIC NOT NULL,   -- dimension degenerada
    PRIMARY KEY (sk_dim_medico, sk_dim_paciente, sk_dim_diagnostico,
                 sk_dim_fecha_elaboracion, num_ingreso)
);

CREATE TABLE dwh.fact_tratamiento (
    sk_dim_medicamento              INTEGER NOT NULL REFERENCES dwh.dim_medicamento (sk_dim_medicina),
    sk_dim_tratamiento              INTEGER NOT NULL REFERENCES dwh.dim_tratamiento (sk_dim_tratamiento),
    sk_dim_fecha_inicio             INTEGER NOT NULL REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    sk_dim_fecha_fin                INTEGER NOT NULL REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    sk_dim_medico                   INTEGER NOT NULL REFERENCES dwh.dim_medico (sk_dim_medico),
    sk_dim_paciente                 INTEGER NOT NULL REFERENCES dwh.dim_paciente (sk_dim_paciente),
    sk_dim_fecha_elaboracion_pres   INTEGER NOT NULL REFERENCES dwh.dim_tiempo (sk_dim_tiempo),
    numero_ingreso                  INTEGER NOT NULL,   -- dimension degenerada
    cant_dias                       NUMERIC,
    PRIMARY KEY (sk_dim_medicamento, sk_dim_tratamiento, sk_dim_fecha_inicio,
                 sk_dim_fecha_fin, sk_dim_medico, sk_dim_paciente,
                 sk_dim_fecha_elaboracion_pres, numero_ingreso)
);

-- =====================================================================
-- TABLA AISLADA (el diagrama indica que no es relevante para las consultas)
-- =====================================================================

CREATE TABLE dwh.dim_registro_epidemiologico (
    -- el diagrama nombra la PK "SK_DIM_INTERVENCION" (copia de otra tabla); se renombra
    sk_dim_registro_epidemiologico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    num_registroe                  NUMERIC,
    cantidad_habi                  INTEGER,
    enfermedad                     VARCHAR(25),
    cant_casos                     INTEGER,
    situacion_actual               VARCHAR(15)
);

-- =====================================================================
-- INDICES sobre llaves foraneas de hechos (Postgres no los crea solo)
-- =====================================================================

CREATE INDEX ix_fact_fact_paciente   ON dwh.fact_facturacion (sk_dim_paciente);
CREATE INDEX ix_fact_fact_servicio   ON dwh.fact_facturacion (sk_dim_tipo_servicio);
CREATE INDEX ix_fact_fact_fecha      ON dwh.fact_facturacion (sk_dim_fecha_facturacion);
CREATE INDEX ix_fact_fact_poliza     ON dwh.fact_facturacion (sk_dim_poliza);
CREATE INDEX ix_fact_fact_estado     ON dwh.fact_facturacion (sk_dim_estado_factura);
CREATE INDEX ix_fact_fact_area       ON dwh.fact_facturacion (sk_dim_area);
CREATE INDEX ix_fact_interv_paciente ON dwh.fact_intervencion (sk_dim_paciente);
CREATE INDEX ix_fact_interv_fecha    ON dwh.fact_intervencion (sk_dim_fecha_practica);
CREATE INDEX ix_fact_diag_paciente   ON dwh.fact_diagnostico (sk_dim_paciente);
CREATE INDEX ix_fact_trat_paciente   ON dwh.fact_tratamiento (sk_dim_paciente);
