-- Esquema relacional OLTP (PostgreSQL)
-- Todas las tablas se crean en el esquema "OLTP"

CREATE SCHEMA IF NOT EXISTS "OLTP";

SET search_path TO "OLTP";

DROP TABLE IF EXISTS "OLTP".PROVEE CASCADE ;
DROP TABLE IF EXISTS "OLTP".TIPO_PROVEE CASCADE ;
DROP TABLE IF EXISTS "OLTP".MEDICINA CASCADE ;
DROP TABLE IF EXISTS "OLTP".APLICA CASCADE ;
DROP TABLE IF EXISTS "OLTP".TRATAMIENTO CASCADE ;
DROP TABLE IF EXISTS "OLTP".PRESCRIBE CASCADE ;
DROP TABLE IF EXISTS "OLTP".CIUDAD CASCADE ;
DROP TABLE IF EXISTS "OLTP".ESTADO CASCADE ;
DROP TABLE IF EXISTS "OLTP".MEDICO CASCADE ;
DROP TABLE IF EXISTS "OLTP".SX CASCADE ;
DROP TABLE IF EXISTS "OLTP".ESTADO_CIVIL CASCADE ;
DROP TABLE IF EXISTS "OLTP".TIENE CASCADE ;
DROP TABLE IF EXISTS "OLTP".ESPECIALIDAD CASCADE ;
DROP TABLE IF EXISTS "OLTP".AREA CASCADE ;
DROP TABLE IF EXISTS "OLTP".TRABAJA CASCADE ;
DROP TABLE IF EXISTS "OLTP".PERSONAL_SANITARIO CASCADE ;
DROP TABLE IF EXISTS "OLTP".DIAGN CASCADE ;
DROP TABLE IF EXISTS "OLTP".CAMA CASCADE ;
DROP TABLE IF EXISTS "OLTP".OCUPA CASCADE ;
DROP TABLE IF EXISTS "OLTP".REALIZA CASCADE ;
DROP TABLE IF EXISTS "OLTP".PRACTICA CASCADE ;
DROP TABLE IF EXISTS "OLTP".PAC CASCADE ;
DROP TABLE IF EXISTS "OLTP".INTERVENCION CASCADE ;

--- tablas
CREATE TABLE "OLTP".ESTADO(
	ID_ESTADO NUMERIC,
	NOMBRE VARCHAR(500),
	CONSTRAINT ESTADO_PK PRIMARY KEY(ID_ESTADO)
) ;

CREATE TABLE "OLTP".CIUDAD(
	ID_CIUDAD NUMERIC,
	NOMBRE VARCHAR(500),
	ID_ESTADO NUMERIC,
    CONSTRAINT CIUDAD_PK PRIMARY KEY(ID_CIUDAD),
	CONSTRAINT ESTADO_FK FOREIGN KEY (ID_ESTADO) REFERENCES "OLTP".ESTADO(ID_ESTADO)
) ;

CREATE TABLE "OLTP".TIPO_PROVEE(
	ID_TIPO NUMERIC,
	DESCRIP VARCHAR(500),
	CONSTRAINT TIPO_PROVEE_PK PRIMARY KEY(ID_TIPO)
) ;

CREATE TABLE "OLTP".PROVEE(
	ID_PROVEE NUMERIC,
	NOMBRE VARCHAR(500),
	RIF VARCHAR(500),
	TELEFONO VARCHAR(500),
	FAX VARCHAR(500),
	ID_TIPO NUMERIC,
	ID_CIUDAD NUMERIC,
	DIRECCION VARCHAR (500),
	CONSTRAINT PROVEE_PK PRIMARY KEY(ID_PROVEE),
	CONSTRAINT TIPO_PROVEE_FK FOREIGN KEY (ID_TIPO) REFERENCES "OLTP".TIPO_PROVEE(ID_TIPO),
	CONSTRAINT CIUDAD_FK FOREIGN KEY (ID_CIUDAD) REFERENCES "OLTP".CIUDAD(ID_CIUDAD)
) ;

CREATE TABLE "OLTP".ESPECIALIDAD(
	ID_ESPECIALIDAD NUMERIC,
	DESCRIP VARCHAR(500),
	CONSTRAINT ESPECIALIDAD_PK PRIMARY KEY(ID_ESPECIALIDAD)
) ;

CREATE TABLE "OLTP".SX (
	ID_SX NUMERIC,
	DESCRIP VARCHAR(500),
	CONSTRAINT SX_PK PRIMARY KEY(ID_SX)
) ;

CREATE TABLE "OLTP".ESTADO_CIVIL (
	ID_ESTADO_CIVIL NUMERIC,
	DESCRIP VARCHAR (500),
	CONSTRAINT ESTADO_CIVIL_PK PRIMARY KEY(ID_ESTADO_CIVIL)
) ;

CREATE TABLE "OLTP".MEDICO (
	CI_MEDICO NUMERIC,
	COD_COLEGIO_MEDICO NUMERIC,
	NOMBRE VARCHAR(500),
	APELLIDO VARCHAR(500),
	F_NACIMIENTO DATE,
	F_CONTRATACION DATE,
	ID_SX NUMERIC ,
	ID_ESTADO_CIVIL NUMERIC ,
	ID_ESPECIALIDAD NUMERIC ,
	ID_CIUDAD NUMERIC,
	CONSTRAINT MEDICO_PK PRIMARY KEY(CI_MEDICO),
	CONSTRAINT MEDICOSX_FK FOREIGN KEY (ID_SX) REFERENCES "OLTP".SX(ID_SX),
	CONSTRAINT MEDICOEC_FK FOREIGN KEY (ID_ESTADO_CIVIL) REFERENCES "OLTP".ESTADO_CIVIL(ID_ESTADO_CIVIL),
	CONSTRAINT MEDICOES_FK FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES "OLTP".ESPECIALIDAD(ID_ESPECIALIDAD),
	CONSTRAINT MEDICOCIU_FK FOREIGN KEY (ID_CIUDAD) REFERENCES "OLTP".CIUDAD(ID_CIUDAD)
) ;

CREATE TABLE "OLTP".TIENE (
	CI_MEDICO NUMERIC ,
	ID_ESPECIALIDAD NUMERIC ,
	ANOS_EXPERIENCIA NUMERIC,
	CONSTRAINT TIENE_PK PRIMARY KEY(CI_MEDICO,ID_ESPECIALIDAD),
	CONSTRAINT TIENEMED_FK FOREIGN KEY (CI_MEDICO) REFERENCES "OLTP".MEDICO(CI_MEDICO),
	CONSTRAINT TIENEES_FK FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES "OLTP".ESPECIALIDAD(ID_ESPECIALIDAD)
) ;

CREATE TABLE "OLTP".AREA(
	ID_AREA NUMERIC,
	ID_ESPECIALIDAD NUMERIC,
	CI_MEDICO_ENCARGADO NUMERIC,
	PISO NUMERIC,
	PASILLO NUMERIC,
	CONSTRAINT AREA_PK PRIMARY KEY(ID_AREA),
	CONSTRAINT AREAESP_FK FOREIGN KEY (ID_ESPECIALIDAD) REFERENCES "OLTP".ESPECIALIDAD(ID_ESPECIALIDAD),
	CONSTRAINT AREAMED_FK FOREIGN KEY (CI_MEDICO_ENCARGADO) REFERENCES "OLTP".MEDICO(CI_MEDICO)
) ;

CREATE TABLE "OLTP".MEDICINA(
	ID_MEDICINA NUMERIC,
	NOMBRE VARCHAR(500),
	PRESENTACION VARCHAR(500),
	POSOLOGIA VARCHAR(500),
	EFECTOS_SECUNDARIOS VARCHAR(500),
	ID_PROVEE NUMERIC,
	CONSTRAINT MEDICINA_PK PRIMARY KEY(ID_MEDICINA),
	CONSTRAINT MED_PROV_FK FOREIGN KEY (ID_PROVEE) REFERENCES "OLTP".PROVEE(ID_PROVEE)
) ;

CREATE TABLE "OLTP".TRABAJA(
	ID_MEDICO NUMERIC ,
	ID_AREA NUMERIC ,
	F DATE,
	CONSTRAINT TRABAJAMED_FK FOREIGN KEY (ID_MEDICO) REFERENCES "OLTP".MEDICO(CI_MEDICO),
	CONSTRAINT TRABAJAARE_FK FOREIGN KEY (ID_AREA) REFERENCES "OLTP".AREA(ID_AREA)
) ;

CREATE TABLE "OLTP".PERSONAL_SANITARIO(
	CI_PERSONAL NUMERIC,
	NOMBRE VARCHAR(500),
	APELLIDO VARCHAR(500),
	FUNCION VARCHAR(500),
	ID_AREA NUMERIC,
	CONSTRAINT PERSONAL_SANITARIO_PK PRIMARY KEY(CI_PERSONAL),
	CONSTRAINT PERSSAN_AREA_FK FOREIGN KEY (ID_AREA) REFERENCES "OLTP".AREA(ID_AREA)
) ;

CREATE TABLE "OLTP".DIAGN(
	ID_DIAGN NUMERIC,
	TIPO VARCHAR(500),
	NOMBRE VARCHAR(500),
	DESCRIP VARCHAR(500),
	COSTO FLOAT,
	CONSTRAINT DIAGN_PK PRIMARY KEY(ID_DIAGN)
) ;

CREATE TABLE "OLTP".CAMA(
	ID_NUMBER_CAMA NUMERIC,
	ID_AREA_HOSPITAL NUMERIC,
	CONSTRAINT CAMA_PK PRIMARY KEY(ID_NUMBER_CAMA),
	CONSTRAINT AREA_FK FOREIGN KEY (ID_AREA_HOSPITAL) REFERENCES "OLTP".AREA(ID_AREA)
) ;

CREATE TABLE "OLTP".TRATAMIENTO(
	ID_TRATAMIENTO NUMERIC,
	DESCRIP VARCHAR(500),
	COSTO FLOAT,
	CONSTRAINT TRATAMIENTO_PK PRIMARY KEY(ID_TRATAMIENTO)
) ;

CREATE TABLE "OLTP".APLICA(
	ID_MEDICINA NUMERIC,
	ID_TRATAMIENTO NUMERIC,
	CANT_DIAS NUMERIC,
	F_INICIO DATE,
	F_FIN DATE,
	CONSTRAINT APLICA_PK PRIMARY KEY(ID_MEDICINA,ID_TRATAMIENTO),
	CONSTRAINT ApliMed_FK FOREIGN KEY (ID_MEDICINA) REFERENCES "OLTP".MEDICINA(ID_MEDICINA),
	CONSTRAINT ApliTrat_FK FOREIGN KEY (ID_TRATAMIENTO) REFERENCES "OLTP".TRATAMIENTO(ID_TRATAMIENTO)
) ;

CREATE TABLE "OLTP".PAC (
	CI_PAC NUMERIC,
	NOMBRE VARCHAR(500),
	APELLIDO VARCHAR(500),
	F_NACIMIENTO DATE,
	TIPO_SANGRE VARCHAR(500),
	NACIONALIDAD VARCHAR(500),
	ID_ESTADO_CIVIL NUMERIC,
	ID_SX NUMERIC,
	ID_CIUDAD NUMERIC,
	CONSTRAINT PAC_PK PRIMARY KEY(CI_PAC),
	CONSTRAINT PACEDC_FK FOREIGN KEY (ID_ESTADO_CIVIL) REFERENCES "OLTP".ESTADO_CIVIL(ID_ESTADO_CIVIL),
	CONSTRAINT PACSEX_FK FOREIGN KEY (ID_SX) REFERENCES "OLTP".SX(ID_SX),
	CONSTRAINT PACCID_FK FOREIGN KEY (ID_CIUDAD) REFERENCES "OLTP".CIUDAD(ID_CIUDAD)
) ;

CREATE TABLE "OLTP".INTERVENCION(
	ID_INTERVENCION NUMERIC,
	DESCRIP VARCHAR(500),
	TIPO VARCHAR(500),
	CONSTRAINT INTERVENCION_PK PRIMARY KEY(ID_INTERVENCION)
) ;

CREATE TABLE "OLTP".PRESCRIBE(
	CI_MEDICO NUMERIC,
	CI_PAC NUMERIC,
	ID_TRATAMIENTO NUMERIC,
	NUMBER_INGRESO NUMERIC,
	F_ELABORACION DATE,
	CONSTRAINT PRESCRIBE_PK PRIMARY KEY(CI_MEDICO,CI_PAC,ID_TRATAMIENTO),
	CONSTRAINT PreMEDICO_FK FOREIGN KEY (CI_MEDICO) REFERENCES "OLTP".MEDICO(CI_MEDICO),
	CONSTRAINT PrePAC_FK FOREIGN KEY (CI_PAC) REFERENCES "OLTP".PAC(CI_PAC),
	CONSTRAINT PreTratamiento_FK FOREIGN KEY (ID_TRATAMIENTO) REFERENCES "OLTP".TRATAMIENTO(ID_TRATAMIENTO)
) ;

CREATE TABLE "OLTP".PRACTICA(
	CI_MEDICO NUMERIC,
	CI_PAC NUMERIC,
	ID_INTERVENCION NUMERIC,
	CI_PERSONAL_SANITARIO NUMERIC,
	F DATE,
	RIESGO VARCHAR(500),
	DURACION NUMERIC,
	GASTO_EQUIPOS FLOAT,
	COSTO FLOAT,
	HONORARIO_EQUIPO FLOAT,
	CONSTRAINT PRACTICA_PK PRIMARY KEY(CI_MEDICO,CI_PAC,ID_INTERVENCION,CI_PERSONAL_SANITARIO),
	CONSTRAINT PracMed_FK FOREIGN KEY (CI_MEDICO) REFERENCES "OLTP".MEDICO(CI_MEDICO),
	CONSTRAINT PracPac_FK FOREIGN KEY (CI_PAC) REFERENCES "OLTP".PAC(CI_PAC),
	CONSTRAINT PracInt_FK FOREIGN KEY (ID_INTERVENCION) REFERENCES "OLTP".INTERVENCION(ID_INTERVENCION),
	CONSTRAINT PracPers_FK FOREIGN KEY (CI_PERSONAL_SANITARIO) REFERENCES "OLTP".PERSONAL_SANITARIO(CI_PERSONAL)
) ;

CREATE TABLE "OLTP".REALIZA (
	CI_MEDICO NUMERIC,
	CI_PAC NUMERIC,
	ID_DIAGN NUMERIC,
	NUMBER_INGRESO NUMERIC,
	F_ELABORACION DATE,
	CONSTRAINT REALIZA_PK PRIMARY KEY(CI_MEDICO,CI_PAC,ID_DIAGN),
	CONSTRAINT RealizaMed_FK FOREIGN KEY (CI_MEDICO) REFERENCES "OLTP".MEDICO(CI_MEDICO),
	CONSTRAINT RealizaPac_FK FOREIGN KEY (CI_PAC) REFERENCES "OLTP".PAC(CI_PAC),
	CONSTRAINT RealizaDiag_FK FOREIGN KEY (ID_DIAGN) REFERENCES "OLTP".DIAGN(ID_DIAGN)
) ;

CREATE TABLE "OLTP".OCUPA (
	CI_PAC NUMERIC,
	ID_NUMBER_CAMA NUMERIC,
	F_INICIO DATE,
	CANTIDAD_DIAS NUMERIC,
	DIAS_CUBIERTOS_SEGURO NUMERIC,
	COSTO_DIARIO NUMERIC,
	ESTATUS VARCHAR(500),
	CONSTRAINT OCUPA_PK PRIMARY KEY(CI_PAC,ID_NUMBER_CAMA),
	CONSTRAINT OcupaPac_FK FOREIGN KEY (CI_PAC) REFERENCES "OLTP".PAC(CI_PAC),
	CONSTRAINT OcupaCam_FK FOREIGN KEY (ID_NUMBER_CAMA) REFERENCES "OLTP".CAMA(ID_NUMBER_CAMA)
) ;
