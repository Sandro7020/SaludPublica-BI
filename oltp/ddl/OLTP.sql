CREATE TABLE "OLTP".OCUPA (
	CI_PAC NUMERIC NOT NULL,
	ID_NUMBER_CAMA NUMERIC,
	F_INICIO DATE,
	CANTIDAD_DIAS NUMERIC,
	DIAS_CUBIERTOS_SEGURO NUMERIC,
	COSTO_DIARIO NUMERIC,
	ESTATUS VARCHAR(500),
	NUMBER_INGRESO NUMERIC NOT NULL,
	ID_POLIZA NUMERIC,
	CONSTRAINT OCUPA_PK PRIMARY KEY(NUMBER_INGRESO,ID_NUMBER_CAMA,F_INICIO),
	CONSTRAINT OcupaPac_FK FOREIGN KEY (NUMBER_INGRESO,CI_PAC) REFERENCES "OLTP".INGRESO(NUMBER_INGRESO,CI_PAC),
	CONSTRAINT OcupaCam_FK FOREIGN KEY (ID_NUMBER_CAMA) REFERENCES "OLTP".CAMA(ID_NUMBER_CAMA),
	CONSTRAINT OcupaPoliza_FK FOREIGN KEY (ID_POLIZA,CI_PAC) REFERENCES "OLTP".POLIZA(ID_POLIZA,CI_PAC),
	CONSTRAINT OCUPA_ESTATUS_CK CHECK (ESTATUS IS NULL OR ESTATUS IN ('ACTIVA','ALTA')),
	CONSTRAINT OCUPA_DIAS_CK CHECK (CANTIDAD_DIAS IS NULL OR CANTIDAD_DIAS > 0),
	CONSTRAINT OCUPA_COBERTURA_CK CHECK (
		DIAS_CUBIERTOS_SEGURO IS NULL
		OR (DIAS_CUBIERTOS_SEGURO >= 0
			AND (CANTIDAD_DIAS IS NULL OR DIAS_CUBIERTOS_SEGURO <= CANTIDAD_DIAS))
	),
	CONSTRAINT OCUPA_COSTO_CK CHECK (COSTO_DIARIO IS NULL OR COSTO_DIARIO >= 0)
) ;

CREATE INDEX OCUPA_CAMA_FECHA_IDX ON "OLTP".OCUPA(ID_NUMBER_CAMA,F_INICIO);
CREATE INDEX OCUPA_INGRESO_IDX ON "OLTP".OCUPA(NUMBER_INGRESO);

