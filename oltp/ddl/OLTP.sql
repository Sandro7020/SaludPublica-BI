CREATE TABLE "OLTP".FACTURA(
	ID_FACTURA NUMERIC,
	NUMBER_INGRESO NUMERIC NOT NULL,
	CI_PAC NUMERIC NOT NULL,
	ID_POLIZA NUMERIC,
	ID_ASEGURADORA NUMERIC,
	TIPO_CLIENTE VARCHAR(20) NOT NULL,
	F_EMISION DATE NOT NULL,
	F_VENCIMIENTO DATE NOT NULL,
	MONTO_TOTAL NUMERIC(14,2) NOT NULL,
	MONTO_CUBIERTO NUMERIC(14,2) NOT NULL,
	MONTO_PACIENTE NUMERIC(14,2) NOT NULL,
	ID_ESTADO NUMERIC NOT NULL,
	F_PAGO DATE,
	MONTO_PAGADO NUMERIC(14,2),
	CONSTRAINT FACTURA_PK PRIMARY KEY(ID_FACTURA),
	CONSTRAINT FacturaIngreso_FK FOREIGN KEY (NUMBER_INGRESO,CI_PAC) REFERENCES "OLTP".INGRESO(NUMBER_INGRESO,CI_PAC),
	CONSTRAINT FacturaPoliza_FK FOREIGN KEY (ID_POLIZA,CI_PAC) REFERENCES "OLTP".POLIZA(ID_POLIZA,CI_PAC),
	CONSTRAINT FacturaAseguradora_FK FOREIGN KEY (ID_POLIZA,ID_ASEGURADORA) REFERENCES "OLTP".POLIZA(ID_POLIZA,ID_ASEGURADORA),
	CONSTRAINT FacturaEstado_FK FOREIGN KEY (ID_ESTADO) REFERENCES "OLTP".ESTADO_FACTURA(ID_ESTADO),
	CONSTRAINT FACTURA_CLIENTE_CK CHECK (
		(MONTO_CUBIERTO > 0
			AND TIPO_CLIENTE = 'ASEGURADORA'
			AND ID_POLIZA IS NOT NULL
			AND ID_ASEGURADORA IS NOT NULL)
		OR
		(MONTO_CUBIERTO = 0 AND TIPO_CLIENTE = 'PACIENTE')
	),
	CONSTRAINT FACTURA_MONTOS_CK CHECK (
		MONTO_TOTAL >= 0 AND MONTO_CUBIERTO >= 0 AND MONTO_PACIENTE >= 0
		AND MONTO_CUBIERTO + MONTO_PACIENTE = MONTO_TOTAL
	),
	CONSTRAINT FACTURA_FECHAS_CK CHECK (
		F_VENCIMIENTO >= F_EMISION
		AND (F_PAGO IS NULL OR F_PAGO >= F_EMISION)
	),
	CONSTRAINT FACTURA_PAGO_CK CHECK (
		(F_PAGO IS NULL) = (MONTO_PAGADO IS NULL)
		AND (MONTO_PAGADO IS NULL OR (MONTO_PAGADO >= 0 AND MONTO_PAGADO <= MONTO_TOTAL))
	),
	CONSTRAINT FACTURA_TIPO_CLIENTE_CK CHECK (TIPO_CLIENTE IN ('PACIENTE','ASEGURADORA'))
) ;

CREATE INDEX FACTURA_PAC_IDX ON "OLTP".FACTURA(CI_PAC);
CREATE INDEX FACTURA_INGRESO_IDX ON "OLTP".FACTURA(NUMBER_INGRESO);
CREATE INDEX FACTURA_EMISION_IDX ON "OLTP".FACTURA(F_EMISION);
CREATE INDEX FACTURA_ESTADO_IDX ON "OLTP".FACTURA(ID_ESTADO);

CREATE TABLE "OLTP".FACTURA_DETALLE(
	ID_DETALLE NUMERIC,
	ID_FACTURA NUMERIC NOT NULL,
	ID_TIPO_SERVICIO NUMERIC NOT NULL,
	ID_REALIZA INTEGER,
	ID_PRESCRIPCION INTEGER,
	ID_PRACTICA INTEGER,
	F_SERVICIO DATE NOT NULL,
	MONTO NUMERIC(14,2) NOT NULL,
	CONSTRAINT FACTURA_DETALLE_PK PRIMARY KEY(ID_DETALLE),
	CONSTRAINT DetalleFactura_FK FOREIGN KEY (ID_FACTURA) REFERENCES "OLTP".FACTURA(ID_FACTURA),
	CONSTRAINT DetalleTipoServicio_FK FOREIGN KEY (ID_TIPO_SERVICIO) REFERENCES "OLTP".TIPO_SERVICIO(ID_TIPO_SERVICIO),
	CONSTRAINT DetalleRealiza_FK FOREIGN KEY (ID_REALIZA) REFERENCES "OLTP".REALIZA(ID_REALIZA),
	CONSTRAINT DetallePrescribe_FK FOREIGN KEY (ID_PRESCRIPCION) REFERENCES "OLTP".PRESCRIBE(ID_PRESCRIPCION),
	CONSTRAINT DetallePractica_FK FOREIGN KEY (ID_PRACTICA) REFERENCES "OLTP".PRACTICA(ID_PRACTICA),
	-- Exactamente un servicio por linea de detalle.
	CONSTRAINT FACTURA_DETALLE_SERVICIO_CK CHECK (
		(CASE WHEN ID_REALIZA IS NOT NULL THEN 1 ELSE 0 END
		+ CASE WHEN ID_PRESCRIPCION IS NOT NULL THEN 1 ELSE 0 END
		+ CASE WHEN ID_PRACTICA IS NOT NULL THEN 1 ELSE 0 END) = 1
	),
	CONSTRAINT FACTURA_DETALLE_MONTO_CK CHECK (MONTO >= 0)
) ;

