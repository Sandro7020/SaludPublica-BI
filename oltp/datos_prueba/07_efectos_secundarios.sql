DO $$
DECLARE
	v_filas INTEGER;
BEGIN
	SELECT count(*) INTO v_filas FROM EFECTO_SECUNDARIO_PACIENTE;
	IF v_filas < 20 THEN
		RAISE EXCEPTION 'Se esperaban al menos 20 efectos secundarios y hay %', v_filas;
	END IF;

	SELECT count(*) INTO v_filas
	FROM EFECTO_SECUNDARIO_PACIENTE e
	JOIN PRESCRIBE p ON p.ID_PRESCRIPCION = e.ID_PRESCRIPCION
	WHERE p.F_INICIO IS NULL OR p.F_FIN IS NULL
	   OR e.FECHA < p.F_INICIO OR e.FECHA > p.F_FIN;
	IF v_filas > 0 THEN
		RAISE EXCEPTION 'Hay efectos fuera del periodo de la prescripcion: %', v_filas;
	END IF;

	SELECT count(*) INTO v_filas FROM EFECTO_SECUNDARIO_PACIENTE
	WHERE GRAVEDAD NOT IN ('LEVE', 'MODERADO', 'GRAVE');
	IF v_filas > 0 THEN
		RAISE EXCEPTION 'Hay efectos con gravedad invalida: %', v_filas;
	END IF;

	SELECT count(*) INTO v_filas FROM EFECTO_SECUNDARIO_PACIENTE
	WHERE DESCRIPCION IS NULL OR trim(DESCRIPCION) = '';
	IF v_filas > 0 THEN
		RAISE EXCEPTION 'Hay efectos sin descripcion: %', v_filas;
	END IF;

	SELECT count(*) INTO v_filas FROM (
		SELECT ID_PRESCRIPCION FROM EFECTO_SECUNDARIO_PACIENTE
		GROUP BY 1 HAVING count(*) > 1
	) d;
	IF v_filas > 0 THEN
		RAISE EXCEPTION 'Hay prescripciones con mas de un efecto: %', v_filas;
	END IF;

	SELECT count(DISTINCT i.ID_AREA) INTO v_filas
	FROM EFECTO_SECUNDARIO_PACIENTE e
	JOIN PRESCRIBE p ON p.ID_PRESCRIPCION = e.ID_PRESCRIPCION
	JOIN INGRESO i ON i.NUMBER_INGRESO = p.NUMBER_INGRESO;
	IF v_filas <> 10 THEN
		RAISE EXCEPTION 'Los efectos no se reparten entre las 10 areas: %', v_filas;
	END IF;

	SELECT count(*) INTO v_filas FROM (
		SELECT i.ID_AREA, count(*) AS efectos
		FROM EFECTO_SECUNDARIO_PACIENTE e
		JOIN PRESCRIBE p ON p.ID_PRESCRIPCION = e.ID_PRESCRIPCION
		JOIN INGRESO i ON i.NUMBER_INGRESO = p.NUMBER_INGRESO
		GROUP BY 1 HAVING count(*) < 2
	) d;
	IF v_filas > 0 THEN
		RAISE EXCEPTION 'Hay areas con menos de 2 efectos: %', v_filas;
	END IF;
END;
$$;
